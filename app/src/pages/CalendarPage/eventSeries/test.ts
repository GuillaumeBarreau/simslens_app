import {
  browserTimeZone,
  buildSeriesPayload,
  buildSeriesUpdatePayload,
  isSeriesOccurrence,
  occurrenceDateOf,
  type SeriesFormValues,
} from '.';

describe('buildSeriesUpdatePayload', () => {
  // Raid du 14/10 à 21:00 - 23:30, heure locale du navigateur.
  const event = {
    startTime: new Date(2026, 9, 14, 21, 0).toISOString(),
    endTime: new Date(2026, 9, 14, 23, 30).toISOString(),
    seriesOccurrenceDate: '2026-10-14T00:00:00.000Z',
  };
  const form = {
    title: 'Renamed',
    description: '',
    startTime: '21:00',
    endTime: '23:30',
    raidDifficultyId: '5',
    isOptional: false,
    signupLockDisabled: true,
  };

  it('leaves the times out when they are unchanged', () => {
    const payload = buildSeriesUpdatePayload(event, form, 'Europe/London');
    expect(payload).toEqual({
      fromDate: '2026-10-14',
      title: 'Renamed',
      description: undefined,
      raidDifficultyId: 5,
      isOptional: false,
      signupLockDisabled: true,
    });
  });

  it('sends changed times with the time zone they were typed in', () => {
    const payload = buildSeriesUpdatePayload(
      event,
      { ...form, startTime: '20:30' },
      'Europe/London',
    );
    expect(payload).toMatchObject({
      startTime: '20:30',
      endTime: '23:30',
      timezone: 'Europe/London',
    });
  });

  it("defaults to the browser's time zone", () => {
    const payload = buildSeriesUpdatePayload(event, { ...form, endTime: '23:00' });
    expect(payload.timezone).toBe(browserTimeZone());
  });
});

const values: SeriesFormValues = {
  title: 'Manaforge - Heroic',
  description: '',
  startTime: '21:00',
  endTime: '23:30',
  raidDifficultyId: '5',
  weeksAhead: 4,
  isOptional: false,
  defaultPresent: true,
  signupLockDisabled: false,
};

describe('buildSeriesPayload', () => {
  it('starts the series on the selected day, with local times', () => {
    expect(buildSeriesPayload(values, new Date(2026, 9, 14, 15, 0), 3, 'Europe/Paris')).toEqual({
      realmId: 3,
      title: 'Manaforge - Heroic',
      description: undefined,
      raidDifficultyId: 5,
      startDate: '2026-10-14',
      startTime: '21:00',
      endTime: '23:30',
      timezone: 'Europe/Paris',
      weeksAhead: 4,
      isOptional: false,
      defaultPresent: true,
      signupLockDisabled: false,
    });
  });

  it('leaves the difficulty out when none is selected', () => {
    const payload = buildSeriesPayload({ ...values, raidDifficultyId: '' }, new Date(), 3, 'UTC');
    expect(payload.raidDifficultyId).toBeUndefined();
  });

  it("defaults to the browser's time zone", () => {
    expect(buildSeriesPayload(values, new Date(), 3).timezone).toBe(browserTimeZone());
  });
});

describe('occurrenceDateOf', () => {
  it('keeps the date of the series, whatever the time zone', () => {
    expect(
      occurrenceDateOf({
        startTime: '2026-10-21T18:00:00.000Z',
        seriesOccurrenceDate: '2026-10-14T00:00:00.000Z',
      }),
    ).toBe('2026-10-14');
  });

  it('falls back on the local start date', () => {
    expect(occurrenceDateOf({ startTime: new Date(2026, 9, 14, 21, 0).toISOString() })).toBe(
      '2026-10-14',
    );
  });
});

describe('isSeriesOccurrence', () => {
  it('detects an event generated by a series', () => {
    expect(isSeriesOccurrence({ seriesId: 9 })).toBe(true);
    expect(isSeriesOccurrence({ seriesId: null })).toBe(false);
    expect(isSeriesOccurrence(null)).toBe(false);
  });
});
