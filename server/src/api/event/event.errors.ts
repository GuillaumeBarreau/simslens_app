export class EventError extends Error {
  statusCode: number;
  code: string;

  constructor(message: string, statusCode: number, code: string) {
    super(message);
    this.name = 'EventError';
    this.statusCode = statusCode;
    this.code = code;
    Error.captureStackTrace(this, this.constructor);
  }
}

/**
 * Thrown when the event does not exist, or belongs to another realm.
 *
 * Les deux cas partagent la même réponse : révéler qu'un événement existe
 * sur un autre royaume serait une fuite d'information.
 */
export class EventNotAccessibleError extends EventError {
  constructor() {
    super('Event not found or access denied', 404, 'not_found');
    this.name = 'EventNotAccessibleError';
  }
}

/**
 * Thrown when the event series does not exist, or belongs to another realm
 * (même réponse dans les deux cas, comme EventNotAccessibleError).
 */
export class EventSeriesNotAccessibleError extends EventError {
  constructor() {
    super('Event series not found or access denied', 404, 'not_found');
    this.name = 'EventSeriesNotAccessibleError';
  }
}

/**
 * Thrown when a series is changed from a date it has not generated yet: the
 * occurrences between the last generated one and that date would silently
 * take the new values.
 */
export class EventSeriesFromDateNotGeneratedError extends EventError {
  constructor() {
    super(
      'fromDate must be the date of an occurrence already generated by the series',
      400,
      'from_date_not_generated',
    );
    this.name = 'EventSeriesFromDateNotGeneratedError';
  }
}

export class RealmIdRequiredError extends EventError {
  constructor() {
    super('realmId is required', 400, 'missing_realm_id');
    this.name = 'RealmIdRequiredError';
  }
}
